<ul><b>
<li>ဆေးထိုးသားဖောက်မျိုးပွားရန်အတွက် သင့်တော်သောငါးမ၊ ငါးထီးများကို ပြုစုကန်မှရွေးချယ်ကြရသည်။</li>

<li>ရေအပူချိန် 26°C မှ 31°C အတွင်း သား‌ဖောက်ရန် သင့်တော်ပါသည်။ ငါးမ၊ ငါးထီးများကိုချိန်တွယ်ပြီး သီးခြားခွဲခြား၍ ခြင်ထောင် (သို့မဟုတ်) ရေ ၂ ပေခန့်ရှိသော အုတ်ကန်ထဲတွင် ထားရှိရမည်။</li>

<li>ငါးမများကို Ovaprim ဟော်မုန်းထိုးဆေးတစ်ကောင်လျှင် 0.4 ml / kg နှုန်းနှင့်အထီးများကိုမူ 0.2 mg / kg နှုန်းဖြင့် ထိုးပေးရသည်။</li>

<li>ဆေးထိုးပြီး ၁ဝ နာရီခန့်အကြာတွင် ငါးမများကို ဥညှစ်ခြင်း(Stripping) ပြုလုပ်ရန်အဆင့်သင့်ဖြစ်ပြီဖြစ်၍ ငါးမများ၏ ဦးခေါင်းပိုင်းကို ရေစိုအဝတ်စဖြင့်ဖုံးအုပ်၍ ဥများကို ဇလုံများထဲသို့ ညှစ်ယူရသည်။</li>

<li> ထို့နောက် ငါးထီးကိုလည်း ခေါင်းကို ရေစိုအဝတ်စဖြင့်ဖုံးအုပ်၍ မျိုးရည်ကို ညှစ်ယူကာ ဇလုံထဲရှိ ငါးဥများပေါ်သို့ကျစေပြီး ကြက်တောင်‌ဖြင့်ကောင်းစွာသမအောင်‌မွှေကာ ရောစပ်ပေးရပါမည်။။ ၁ မိနစ်၂ မိနစ်ခန့်မွှေပေးရပါမည်။</li>

<li>ထို့နောက်ယင်းဥများပေါ်သို့ (ဆား + Carbamide ) ဖျော်ရည်ကို ဥများမြုပ်သည်ထိ လောင်းပေးမွှေထားပေးပြီး ယင်းဖျော်ရည်ဖြင့် ၂ ကြိမ်ခန့်ဆေးကြောပေးရပါမည်။</li>

<li>ဆက်လက်၍ ဥများကို မကပ်‌စေရန်Tunnin ဆေးဖျော်ရည် (5gm /10 lit) ထဲသို့ လောင်းထည့်ပြီး ၅ စက္ကန့်ခန့်မွှေပေးပြီးနောက် ရေသန့်ဖြင့်ကောင်းမွန်စွာဆေးကြောပေးရမည်။ ထိုအခါဥများ၏ စေးကပ်မှုပျောက်သွားလိမ့်မည်။</li>

<li> ထို့နောက်ဥဖောက်ရေလည်ကတော့များထဲသို့ ထည့်သွင်းဖောက်ယူနိုင်ပါသည်။ ဥဖောက်ရေလည်ကတော့ထဲ၌ ရေအပူချိန် 28°C မှ 31°C အတွင်း၂၄ နာရီမှ ၃၆ နာရီအကြာတွင်ဥမှငါးမှုန်များပေါက်လာမည်။</li>

<li>ငါးမှုန်များမှာ ၂ ရက်အတွင်း ဥအစာအိတ်ကုန်ခမ်းသွားမည်ဖြစ်၍ အမြန်ဆုံးပြုစုရန်မြေသားကန်ထဲသို့ ထည့်သွင်းရမည်ဖြစ်သည်။</li>

<li>ဥမှပေါက်ပြီး ၃၆ နာရီအတွင်း မြေသားကန်ထဲသို့ ထည့်ပေးရမည်ဖြစ်သည်။</li>

<li>ငါးမှုန်ပြုစုကန်မြေကန်များအတွင်းသို့ အော်ဂဲနစ်မြေဩဇာများ ကြိုတင်ထည့်သွင်းပြီး သတ္တမျှော (Monia)များကို ပွားများလာအောင် ပြုလုပ်ပေးရမည်။ကန်ထဲသို့လွှတ်လိုက်သောငါးမှုန်များက ပထမဆုံး အစာအဖြစ်သတ္တမျှော(Moina) များကို စားသုံးကြမည် ဖြစ်သည်။</li>

<li>(၁၀)ရက်ခန့်အကြာ၌ ငါးမှုန်စာအဖြစ် ငါးပေါင်းမှုန့်  ၅၀%နှင့် ဖွဲနုကို ရောစပ်ကာ ၃၅% ပရိုတိန်းအစာအဖြစ် တစ်နေ့  ၂ ကြိမ်မှ ၃ ကြိမ်ခန့် ကျွေး‌ပေးရပါမည်။ ၁ လခန့်မြေသားကန်ထဲ၌ပြုစုပြီး‌နောက် 14လက်မအရွယ်သို့‌ေရာက်ရှိနိုင်ပါသည်။</li></b>
