<h2 align="center">လှောင်အိမ်ဖြင့်ငါးမွေးမြူခြင်း</h2>
<h3> လှောင်အိမ်အရွယ်အစား</h3>

<p>တီလားပီးယားမွေးမြူရန်အတွက် လှောင်အိမ်ဧရိယာသည် (၁၆)မီတာပတ်လည်မှ (၃၆)မီတာပတ်လည်အထိ ရှိနိုင်ပြီး အမြင့်အားဖြင့် (၂)မီတာမှ (၃)မီတာအထိ မြင့်နိုင်ပါသည်။ တရုတ်နိုင်ငံတွင် ရေပေါ်လှောင်အိမ်များကို အများဆုံးအသုံးပြုကြပါသည်။</p>
<img src="fh1.jpg" class="one">


<p>လှောင်အိမ်များသည် ရေစီးဆင်းမှုကောင်းစေရန်နှင့် ရေလဲလှယ်မှုကောင်းစေရန် အကွာအဝေးအတိုင်းအတာတစ်ခုအထိခြား၍ တစ်ခုနှင့်တစ်ခုကို အစီအရီထားရပါမည်။</p>

<p>ပိုက်လှောင်အိမ်များတွင် အသုံးပြုသောပိုက်၏ ပိုက်ကွက်အရွယ်အစားသည် ထည့်သွင်းမွေးမြူသည့်ငါးအရွယ်အစားပေါ်မူတည်၍ အမျိုးမျိုးဖြစ်နိုင်ပါသည်။</p>
<img src="fh2.jpg" class="two">


<p>ငါးအရွယ် ပျမ်းမျှ(၃.၉)စင်တီမီတာအလျားရှိသော ငါးများထည့်သွင်းမွေးမြူရန်အတွက် ပိုက်ကွက်အရွယ်(၁)စင်တီမီတာအကျယ်မှ စတင်၍ တဖြည်းဖြည်းချင်းတိုးလာပြီး (၁၁.၆)စင်တီမီတာ အရွယ် ရှိသောငါးများအတွက်ဆိုပါက ပိုက်ကွက်အရွယ်(၃.၀)စင်တီမီတာ ပိုက်ကို အသုံးပြုရပါမည်။ တစ်နည်းအားဖြင့်မူ ငါးအရွယ် (အလျား)၏ ၂၅ ရာခိုင်နှုန်းရှိသော ပိုက်ကွက်အရွယ်ရှိပိုက်ကို အသုံးပြုရပါမည်။</p>

<p>မွေးမြူထားသောငါးများကို ငှက်များ ထိုးသုတ်စားခြင်းမှကာကွယ်ရန်နှင့် ငါးများခုန်ကျော်လွတ် မြောက်သွားခြင်းမှကာကွယ်ရန် လှောင်အိမ်များကို အဖုံးဖုံးထားရပါမည်။ အကယ်၍ ကြီးမားသော နိုင်လွန်လှောင်အိမ်များ၏ အပေါ်အစွန်းသည် ရေမျက်နှာပြင်အထက် (၁)ပေ (သို့မဟုတ်) (၂)ပေ အထက်မြင့်နေပါကမူ များသောအားဖြင့် လှောင်အိမ်အဖုံးများကို ဖယ်ထားတတ်ပါသည်။</p>

<h3> လုပ်ငန်းသုံးပစ္စည်းများ</h3>

<p>ငါးမွေးလှောင်အိမ်အတွက် အသုံးပြုမည့် ပစ္စည်းကိရိယာအားလုံးသည် တာရှည်ခံရပါမည်။ အဆိပ်မဖြစ်စေရပါ။ အလေးချိန် ပေါ့ပါးပြီးစျေးမကြီးရပါ၊ သံချေးမတက်သော ပစ္စည်းဖြစ်ရမည်၊ ကော့ပါးနှင့် ဇင့်တို့သည် အဆိပ်ဖြစ်စေနိုင်ပါသည်။ </p>

<p>သံချေးမတက်အောင် ဖုံးကာထားသော ဝိုင်ယာကြိုးများကို ယခင်က အသုံးပြုခဲ့ကြသော်လည်း အဆိုပါအကာများမှာ တစ်နှစ်ကြာပြီးနောက် ကွာကျသွားသဖြင့် မျက်နှာပြင်ကြမ်းများနှင့် ပွတ်တိုက်မိပြီး ငါးများဒဏ်ရာအနာတရ ဖြစ်နိုင်ပါသည်။ ထို့ကြောင့် များသောအားဖြင့်ပလတ် စတစ်ပိုက်လှောင်အိမ်များကိုသာ အသုံးပြုကြပါသည်။</p>
<img src="fh3.jpg" class="three">


<p>ပိုက်လှောင်အိမ်များကို ရေပေါ်ဆွဲတင်ပြီး ကမ်းပေါ်ရှိ ကန်ပေါင်ပေါ်တွင် သိမ်းဆည်းခြင်းထက် လှောင်အိမ်ကို တစ်နှစ်ပတ်လုံး ရေထဲထားပြီး ကန်ထဲ၌ပင် နေလှန်းအခြောက်ခံ၍ ပြန်လည်အသုံးပြုခြင်းက ပို၍ကောင်းမွန်ပါသည်။</p>

<p>ဂဟေဆက်ထားသော ဝိုင်ယာပိုက်ကွက်များသည် တာရှည်ခံပြီး မာကျော၍ ဆွေးမြေ့ခြင်းကို ပို၍ ခံနိုင်ရည်ရှိပြီး ဆွဲနိုင်ဆန့်နိုင်သောပစ္စည်းများထက် သန့်ရှင်းရာတွင် ပို၍ လွယ်ကူပါသည်။ သို့သော် အတော်အသင့်လေးလံ၍ ဝန်လေးပါသည်။ </p>

<p>ပလတ်စတစ်ဖြင့်ပြုလုပ်သော ပိုက်များသည် တာရှည်ခံပြီး အတော်အသင့်မာကျော၍ အလေးချိန်ပေါ့ပါးပြီး ဝိုင်ယာပိုက်ကွက်များထက် စျေးနှုန်းပိုသက်သာပါသည်။ နိုင်လွန်ပိုက်ဖြင့်ပြုလုပ်သော လှောင်အိမ်များသည် အခြားသောပစ္စည်းများဖြင့်တည်ဆောက်ထားသော လှောင်အိမ်များကဲ့သို့အရွယ်အစားဆိုင်ရာ အခက်အခဲများ မရှိပါ။</p>

<p>နိုင်လွန်ပိုက်သည် စျေးသိပ်မကြီးဘဲ အတော်အသင့်ခံနိုင်ရည်ကောင်းမွန်၍ အလေးချိန်ပေါ့ပါးပြီး ကိုင်တွယ်၍ လွယ်ကူပါသည်။ နိုင်လွန်ပိုက်သည်  ကိုက်ဖြတ်တတ်သော လိပ်၊ ဖျံ၊ မိကျောင်းနှင့် ကဏန်းများကြောင့် ထိခိုက်ပျက်စီးတတ်ပါသည်။ အဆိုပါ နိုင်လွန်လှောင်အိမ်များ၏ အပြင်ဘက်တွင် ပိုက်ကွက်ကျယ်ပြီး ပိုမိုခိုင်မာသောလှောင်အိမ်နောက်တစ်လုံးကို တပ်ဆင်ထားရန် လိုအပ်ပါမည်။</p>

<h3> လှောင်အိမ်တစ်လုံးတည်ဆောက်ခြင်း</h3>
<ul>
<li>ဖရိန်ကွင်းများကိုဖြတ်၍ အတူတကွ ကော်ဖြင့်ကပ်ပါ။</li>
<li>ပိုက်လှောင်အိမ်နံရံအတွက် (၁၈)ပေရှိသော နိုင်လွန်ပလတ်စတစ်ပိုက်ကွက်ကို အလျား(၁၀)ပေ (၄)လက်မ အရွယ်ရအောင်ဖြတ်ပါ။ ကျန်ရှိနေသောပိုက်စများကို ဖရိန်ကွင်း(၂)ကွင်းချည်၍ ၄င်းတို့၏ဘေးစများကို ထိပ်စနှင့် အောက်စများအတွက် ဖြတ်ပါ။</li>
<li>ကွင်းများကို ပိတ်စများအောက်တွင်ထားရှိခြင်းသည် အလွယ်ကူဆုံးဖြစ်ပြီး ထို့နောက် ကပ်ကြေးဖြင့်ကွင်း၏အပြင်ဘက်တစ်ဝိုက်ကို တိပေးပါ။</li>
<li>ကေဘယ်လ်ကြိုး (၆) ချောင်းမှ (၈) ချောင်းကို အသုံးပြု၍ ဖရိန်ကွင်းတစ်ကွင်း၏အပြင်ဘက်ဖြင့် လှောင်အိမ်၏နံရံကို တွဲချည်ပါ။ ပိတ်စအထဲတွင် လေးဒေါင့်ပုံ (သို့မဟုတ်) စိန်ပုံလိုင်းများအပြည့် ထိပ်ပိုင်း၌ ဖရိန်ကွင်းကိုတပ်ဆင်ပါ။</li>
<li>လှောင်အိမ်၏နံရံကို(၄)လက်မခန့်ထပ်ပေးပါ။ နောက်အဆင့်အတွက် ပိုက်များကို ကေဘယ်လ်ကြိုးဖြင့်တွဲချည်ထားပါ။ တစ်နေရာတည်း၌ လည်စီး(၃)ခုကို ထပ်ပြီးချည်ထားပါ။</li>
<li>လှောင်အိမ်နံရံများကို (၁လက်မ၏ ၈ ပုံ၁ ပုံရှိသော နိုင်လွန်ကြိုး) အသုံးပြု၍ ဖရိန်ကွင်းနှင့် ပိုက်ကွက်ထိပ်ပိုင်း အစဉ်လိုက်ကို ချည်ထိုးရပါမည်။ အစပြုသောပိုက်ထုံးကို သေချာစွာပြုလုပ်ပြီး ပိုက်ကွက်ထိပ်ပိုင်းကွင်းများကို နှစ်ကွက်ကျော် အစဉ်အတိုင်းကျော်ပြီး ချည်ထိုး၍ ကွင်းပြည့်သွားသောအခါ လျော့ကျနေသောနေရာများကို ဖယ်ပစ်ပါ။ ကွင်းပတ်လည်တွင် နောက်ထပ်အထုံးကို ချည်နှောင်ပါ။</li>
<li>ကြိုး၏နောက်အစတစ်ခုကိုဖြတ်ပြီး အစွန်းတစ်ဖက်နှင့် အခြားအစွန်းတစ်ဖက်ကိုထပ်၍ ချည်နှောင်ရပါမည်။ နောက်တစ်ကြိမ် လျော့ကျသောနေရာကို ဖယ်ရှားပြီး ပိုက်ကွက်(၂) ကွက်ကျော်တိုင်း ချည်နှောင်ရပါမည်။</li>
<li>လှောင်အိမ်၏အောက်ပိုင်းတွင် ပိုက်ထုံးတစ်ခုကို ချည်နှောင်ပြီး ပိုက်ကွက်အစွန်းတစ်စနှင့် အခြားအစွန်းတစ်စကို ထပ်ပိုး၍ ချည်နှောင်ရပါမည်။ ထိုကဲ့သို့ ထပ်ပိုးချည်နှောင်ရာတွင် အရေးကြီးသည့်အချက်မှာ ပြားကပ်နေရမည်ဖြစ်ပြီး ကွက်လပ်များ၊ အပေါက်များ(သို့မဟုတ်) ခေါက်ထားသောနေရာများမှာ လွတ်နေပြီး ငါးများလွတ်ထွက်မသွားစေရန် အလွန်အရေးကြီးပါသည်။</li>
<li>လှောင်အိမ်ကို ပြောင်းပြန်လှန်လိုက်သောအခါ ပိုက်စ၏ထိပ်ပိုင်း လိုင်းနေရာအပြည့်အတွင်း ဒုတိယဖရိန်ကွင်းတစ်ခုကို ထားရှိ၍ ကေဘယ်ကြိုးအနည်းငယ်ဖြင့် သေချာစွာချည်နှောင်ရပါမည်။</li>
<li>အပေါက်ကိုကျော်ပြီး (၃၈ လက်မအချင်း)ရှိသော လှောင်အိမ်အောက်ဖက်ပိုက်စကိုထားရှိပြီး လှောင်အိမ်နံရံကို ဖရိန်ကွင်းနှင့် အောက်ပိုင်းပိုက်စကို တစ်စုတည်းချည်နှောင်ရပါမည်။ ထပ်မံ၍ ကွက်လပ်၊ အပေါက်များရှိမနေရန် သတိပြုရပါမည်။</li>
<li>ပိုက်လှောင်အိမ်ချုပ်သည့်အခါ ချည်ကြိုးများကို အပြင်ဘက်သို့ ပြန်ပို့ပေးရန် နောက်လူတစ်ယောက်သည် လှောင်အိမ်အတွင်းဘက်၌ ရှိနေစေပါက အကူအညီဖြစ်စေပါသည်။</li>
<li>နောက်လူ၏ အရပ်အပေါ်မူတည်၍ ကုလားထိုင်(၃)လုံးအပေါ် လှောင်အိမ်ကိုထားရှိပြီး မြင့်ထားခြင်းဖြင့်ချည်နှောင်ရာတွင် ပို၍ လွယ်ကူစေပါသည်။</li>
<li>အဖုံးအတွက် နောက်ဆုံးဖရိန်ကွင်းကို(၃၈)လက်မရှိသော နောက်ထပ်ပိုက်စဖြင့် ချည်နှောင်ရပါမည်။ ချုပ်ချက်နေရာကို ပိုက်ကွက်နှစ်ကွက်ကျော်၍ ချုပ်သွားရပါမည်။ ငါးများ ထည့်သွင်းပြီးသောအခါ ကြိုးအတိုဖြင့် လှောင်အိမ်ထိပ်ပိုင်းနှင့် အဖုံးကို ချည်နှောင်ထားရပါမည်။ အရိပ်ရစေရန် လှောင်အိမ်အဖုံးကို အခြားသောအရိပ်ရအပါးစနှင့် ပေါ့ပါးသောပစ္စည်းများဖြင့် ချည်နှောင်ထားရပါမည်။</li>
<li>လှောင်အိမ်၏ထိပ်ဖက် အပွင့်ပိုင်းအတွင်းဘက်တွင် ပိတ်ဖြင့်ပြုလုပ်သော( ၁ လက်မ၏ ၈ ပုံ၁ ပုံ)ရှိသော ပိုက်ကွက်အစကို အစာကျွေးကွင်းတစ်ခုပြုလုပ်၍ ကေဘယ်ကြိုးဖြင့်ချည်နှောင်ထားရပါမည်။ အစာကျွေးကွင်းကို လှောင်အိမ်နံရံဖြင့် အပေါ်ပိုင်းရော အောက်ပိုင်းပါ ချည်ထားရပါမည်။</li>
<li>လှောင်အိမ်ကို ရေပေါ်ပေါ်စေသည့်ဘောများဖြင့် နေရာချပြီး ချည်နှောင်ထားခြင်းဖြင့် ရေမျက်နှာ ပြင်အထက်(၄)လက်မခန့် လှောင်အိမ်အထက်ပိုင်းသည် ရေပေါ်ပေါ်နေပါသည်။ တစ်ဂါလံပုံးအလွတ်(၄) လုံးသည် လှောင်အိမ်တစ်လုံးကို လွယ်ကူစွာရေပေါ်ပေါ်နေစေလိမ့်မည် ဖြစ်ပါသည်။</li>
<li>ဂါလံပုံး၏အောက်ဖက်ကို အပေါက်အနည်းငယ်ဖောက်ထားပေးခြင်းဖြင့် ရေအနည်းငယ်ဝင်ပြီး လှောင်အိမ်ကို ပိုပြီးငြိမ်စေပါသည်။</li>
</ul>
<h3>လှောင်အိမ်များတပ်ဆင်ခြင်း</h3>
<ul>
<li>လှောင်အိမ်များကို ရေစီးကြောင်းအထူးကောင်းမွန်သောရေပြင်၌ လေတိုက်လာသည့်ဘက်သို့ များသောအားဖြင့် နေရာချထားလေ့ရှိပါသည်။ လှောင်အိမ်ဖြင့်ငါးမွေးမြူခြင်းကို ထိခိုက်စေသည့် အလွန်အရေးကြီးသောလုပ်ငန်းတစ်ရပ်မှာ လှောင်အိမ်များကိုနေရာချထားခြင်းလုပ်ငန်းရပ်ဖြစ်ပါသည်။</li>
<li>ငါးများမှ စွန့်ထုတ်အညစ်အကြေးများနှင့် လှောင်အိမ်ကိုဖြတ်၍ အောက်ကျသွားသောအစာကျန်များနှင့်လှောင်အိမ်ထားရှိသော အနီးကပ်နေရာမှ အဝေးသို့မျောပါခြင်းတို့သည် အလွန်အရေးကြီးပါသည်။</li>
<li>ထို့ကြောင့် ငါးမွေးလှောင်အိမ်များကို ကန်အောက်ခြေနှင့် လှောင်အိမ်အောက်ခြေအကြား အနည်းဆုံး (၂)ပေကွာခြားနိုင်မည့်နေရာတွင် ထားရှိရပါမည်။ ငါးမွေးလှောင်အိမ်၏ အနီး၌ အညစ်အကြေးများ စုပုံနေခြင်း မဖြစ်စေရပါ။</li> 
<li>လှောင်အိမ်ပုံသေများကိုမူ အောက်ခြေကြမ်းပြင်ရှိ ရွံ့ထဲသို့ စိုက်ထူထားသောတိုင်များဖြင့် ချည် နှောင်ထားရှိရပါမည်။ အဆိုပါနေရာ၌ ရေပေါ်ပေါ်သော လှောင်အိမ်များအတွက်မူ ရေပြင်၏မျက်နှာပြင်တွင် တည်ရှိစေမည့် ရေပေါ်ပေါ်စေသောအရာတစ်ခု လိုအပ်မည်ဖြစ်ပါသည်။</li>
<li>လှောင်အိမ်များကို ငါးများခုန်ထွက်မသွားစေရန်နှင့် ငှက်များထိုးသုတ်စားခြင်းမှ ကာကွယ်ရန်အတွက် အဖုံးများ ဖုံးအုပ်တပ်ဆင်ထားရှိရပါမည်။</li>
<li>အစာဆုံးရှုံးလေလွင့်မှု အနည်းဆုံးဖြစ်စေရန် လှောင်အိမ်အတွင်း၌ တစ်လက်မ၏ ရှစ်ပုံတစ်ပုံ (သို့မဟုတ်) ထို့ထက်ပို၍ပိုက်ကွက်သေးငယ်သောပိုက်ကွက်ငယ်များဖြင့် ပြုလုပ်ထားသော အစာကျွေးဗန်း(သို့မဟုတ်) အစာကျွေးကွင်းများကိုနေရာချထားခြင်း လုပ်ဆောင်ရပါမည်။</li>
<li>လှောင်အိမ်အနီးတွင်ရေကူးခြင်း၊ မော်တော်ခုတ်မောင်းခြင်း ငါးဖမ်းခြင်းလုပ်ငန်းရပ်များဖြစ်သည့် မွေးမြူထားသောငါးများကို အနှောင့်အယှက်ပေးခြင်းအား မပြုလုပ်စေရပါ။</li>
</ul>
