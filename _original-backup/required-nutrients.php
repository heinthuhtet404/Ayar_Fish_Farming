<h3>ပရိုတင်းနှင့်အမိုင်နိုအက်စစ်</h3>
<p><b>ပရိုတင်းနှင့်အမိုင်နိုအက်စစ်သည်သတ္တလောကရှိသတ္တဝါအားလုံး၏ဇီ၀ကမ္မဖြစ်စဉ်များအတွက်အလွန်‌အရေးပါသောဓာတ်ပစ္စည်းများဖြစ်သည်။ပရိုတင်းဓာတ်ပြိုကွဲသောအခါကာဗွန်(၅၀%)၊နိုက်ထြိုဂျင်(၁၆%)၊အောက်စီဂျင်(၂၁.၅%)၊ဟိုက်ဒြိုဂျင်(၆.၅%)ပါ၀င်သည်ကိုတွေ့ရှိရသည်။ယင်းဓာတ်များသည်အချိုးအစားအလိုက်အမိုင်နိုအက်စစ်နှင့်ကြွက်သား၊တစ်ရှူး၊သွေး၊အင်ဇိုင်း၊ဟော်မုန်းစသည်တို့တည်ဆောက်မှုအထောက်အကူပြုပါသည်။ရေသတ္တဝါမွေးမြူရေးအစာ၏ပရိုတင်းလိုအပ်ချိန်မှာယေဘုယျအားဖြင့်ရေငန်ပုစွန်၂၅-၅၀%၊ငါးတန်၂၈-၃၈%၊ငါးကြင်းအုပ်စု၂၅-၄၀%၊ငါးရံ့၃၀-၅၀%ဖြစ်ပါသည်။</b></p>
<h2>(ခ) ပမာဏအနည်းငယ်သာအသုံးပြုရသောဓာတ်ပစ္စည်းများ</h2>
<p><b>ယင်းပစ္စည်းများမှာဗိုက်တာမင်နှင့်သတ္ထုဓာတ်များဖြစ်ပြီးပမာဏအနည်းငယ်သာအသုံးပြုရသည်။</b></p>
<h3>ဗိုက်တာမင်</h3>
<p><b>ရေတွင်ပျော်၀င်သောဗိုက်တာမင်ဘီအုပ်စုနှင့်စီအုပ်စု၊ဆီတွင်ပျော်၀င်သောအေ၊ဒီ၊အီးနှင့်ကေဟူ၍အုပ်စုနှစ်မျိုးခွဲခြားထားပါသည်။ရေတွင်ပျော်၀င်သောအုပ်စုတွင်ပါ၀င်သောဗိုက်တာမင်စီသည်ရောဂါကိုခုခံကာကွယ်နိုင်စွမ်းရှိသောငါး၏ကိုယ်တွင်းအဂ်ါအတွက်အရေးပါသောဓာတ်ပစ္စည်းဖြစ်ပြီးဖိစီးမှုနှင့်ပတ်သက်သောဒဏ်များကိုလည်းသက်သာစေပါသည်။ဆီတွင်ပျော်၀င်သောဗိုက်တာမင်ဓာတ်များသည်အစာတွင်ပါ၀င်သောအဆီဓာတ်ကိုခန္ဓာကိုယ်အတွင်းဖြန့်ဝေရာတွင်များစွာအထောက်အကူပြုပါသည်။</b></p>
<h3>သတ္ထုဓာတ်</h3>
<p><b>ရေသတ္တဝါများအတွက်အဓိကလိုအပ်ချက်မှာကုန်းသတ္တဝါများနှင့်နှိုင်းယှဉ်လျှင်သုတေသနပြုမှုအချက်အလက်များ၊သတင်းရရှိမှုများအလွန်နည်းပါးသည်။အဓိကအားဖြင့်အများလိုအုပ်စုနှင့်အနည်းလိုအုပ်စုဟူ၍နှစ်မျိုးခွဲခြားထားပါသည်။အများလိုအုပ်စုတွင်ဆိုဒီယမ်၊ကလိုရင်း၊ပိုတက်ဆီယမ်၊ကယ်လ်ဆီယမ်၊မဂ္ဂနီဆီယမ်၊ဆာလဖော့နှင့်ဖော့စဖရပ်တို့ပါ၀င်သည်။အရိုး အသား တစ်သျှူးများ ဖြစ်တည်မှုနှင့်ဖွံ့ဖြိုးမှုအတွက်အဓိကလိုအပ်သည်။အများလိုအုပ်စုတွင်ဆိုဒီယမ်၊ကလိုရင်း၊ပိုတက်ဆီယမ်၊ကယ်လ်ဆီယမ်၊မဂ္ဂနီဆီယမ်၊ဆာလဖော့နှင့်ဖော့စဖရပ်တို့ပါ၀င်သည်။အရိုး အသား တစ်သျှူးများ ဖြစ်တည်မှုနှင့်ဖွံ့ဖြိုးမှုအတွက်အဓိကလိုအပ်သည်။</b></p>
<h2>(ဂ) စွမ်းအင်အသုံးချမှု</h2>
<p><b>ငါးများတွင်အောက်ဖော်ပြပါအချက်များအတွက်စွမ်းအင်လိုအပ်ပါသည်။စွမ်းအင်သည်အစာမဟုတ်ပါ။အစာကိုဖြိုခွဲလိုက်သည့်အခါထွက်ပေါ်လာသည့်(ပရိုတင်း၊အဆီဓာတ်၊ကာဗိုဟိုက်ဒြိတ်)တို့မှရရှိသည်။</b></p>
