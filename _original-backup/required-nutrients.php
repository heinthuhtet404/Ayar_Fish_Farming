<h1 align="center">ငါးကျန်းမာရေးအတွက်လိုအပ်သောအာဟာရဓာတ်</h1>
<p><b>ငါးများကြီးထွားရန်၊ကျန်းမာရန်၊ငါးထုတ်ကုန်အရည်အသွေးကောင်းရန်နှင့်ငါးမှစွန့်ထုတ်ပစ္စည်းများသံသရာလည်မှုတို့အတွက်အာဟာရဓာတ်သည်အရေးပါသောအခန်းကဏ္ဍမှပါ၀င်ပါသည်။ငါးမွေးမြူရေးတွင်အစာအတွက်ကုန်ကျစရိတ်သည်စုစုပေါင်းထုတ်လုပ်မှုစရိတ်၏၅၀%ရှိပြီး၊ကန်ကြပ်မွေးမြူရေးစနစ်တွင်မူ၆၀မှ၇၀%အထိကုန်ကျပါသည်။ထို့ကြောင့်စီးပွားဖြစ်ထုတ်လုပ်သောအစာများတွင်ပေးရသောတန်ဖိုးနှင့်ထိုက်တန်သောအာဟာရတန်ဖိုးကိုရရှိစေသောအစာကိုရရှိ‌ရန်အလွန်အရေးကြီးပါသည်။</b></p>
<h2>(က) အများဆုံးလိုအပ်သောအာဟာရဓာတ်</h2>
<h3>စွမ်းအင်ထုတ်အာဟာရဓာတ်များ</h3>
<p><b>ငါးမွေးသူများအများအားဖြင့်အသုံးပြုသောပြည့်၀အစာတွင်ပါ၀င်သောအဟာရတန်ဖိုးမှာအသားဓာတ်(ပရိုတင်း) ၁၈%၊အဆီဓာတ်၁၀-၂၅%၊ကစီဓာတ်(ကာဗိုဟိုက်ဒြိတ်)၁၅-၂၀%၊ပြာဓာတ်(<၈.၅%)၊ဖော့စဖရတ်(<၁.၅%)၊ရေဓာတ်(<၁၀%)၊ဗိုက်တာမင်နှင့်သတ္ထုဓာတ်အနည်းငယ်စီပါ၀င်ပါသည်။ပြည့်၀အစာကိုအဆောက်အဦးအတွင်းကန်ကြပ်မွေးစနစ်နှင့်လှောင်‌အိမ်မွေးစနစ်များတွင်အသုံးပြုပါသည်။ဖြည့်စွက်အစာကိုသဘာ၀အစာဖြစ်သောအပင်မျှောလှေး၊သတ္တမျှောလှေး၊ငါးသေးငါးနုတ်များ ပေါများစွာရရှိသောမြေကန်နှင့်ရေအရှင်လှည့်လည်မွေးမြူသောစနစ်များတွင်အသုံးများပါသည်။ဖြည့်စွက်အစာတွင်ဗိုက်တာမင်နှင့်သတ္ထုဓာတ်တို့ပြည့်၀စွာပါ၀င်ခြင်းမရှိသော်လည်းသဘာ၀အစာမှရရှိသောအသားဓာတ်(ပရိုတင်း၊ကစီဓာတ်(ကာဗိုဟိုက်ဒြိတ်)၊အဆီဓာတ်တို့ကထူးခြားသောအာဟာရအုပ်စုများဖြစ်ပြီးခန္ဓာကိုယ်အတွင်းဓာတုဓာတ်ပြောင်းဖြစ်စဉ်ဖြင့်စွမ်းအင်ထုတ်ပေးကာဇီ၀ကမ္မပြောင်းလဲမှုနှင့်ရုပ်ပိုင်းဆိုင်ရာပြောင်းလဲမှုများနှင့်မွေးမြူထားသောငါးများအတွက်ကြီးထွားမှုကိုအထောက်အကူပြုစေပါသည်။</b></p>
<h3>အဆီဓာတ်</h3>
<p><b>အဆီဓာတ်တွင်ဆီ၊အဆီ၊ဖယောင်းတို့နှင့်ဆက်နွှယ်နေဒြပ်ပေါင်းများပါ၀င်ပါသည်။အဆီဓာတ်သည်ငါးနှင့်ရေသတ္တဝါများအတွက်အောက်ဖော်ပြပါလုပ်ဆောင်ချက်များကိုလုပ်ဆောင်ပေးပါသည်။</b></p>
<ul><b>
	<li>မရှိမဖြစ်လိုအပ်သောဖက်တီးအက်စစ်(Fatty Acid)ကိုရရှိစေသည်။</li>
	<li>ခန္ဓာကိုယ်အတွင်းစွမ်းအင်ဓာတ်များကိုအဆီဓာတ်အနေဖြင့်သိုလှောင်ပေးသည်။</li>
	<li>ဆဲလ်နံရံများအမှေးပါးများအတွက်အရေးပါသောမရှိမဖြစ်လိုအပ်သောဖေါ့စဖရပ်ဓာတ်ပါ၀င်သောအဆီဓာတ်ကိုရရှိစေခြင်း</li>
	<li>စတီးရွိုက်ဟော်မုန်း၏ဆဲလ်တစ်ခုနှင့်တစ်ခုအကြားဆက်သွယ်ခြင်းနှင့်ဇီ၀ဆိုင်ရာထောက်ပံ့မှုများကိုလုပ်ဆောင်ပေးခြင်း</li>
	<li>ဆီတွင်ပျော်၀င်သောဗိုက်တာမင်ဓာတ်များကိုခန္ဓာကိုယ်အတွင်းသယ်ဆောင်ပေးခြင်း</li>
	<li>အဆီဓာတ်သည်မရှိမဖြစ်လိုအပ်သောကိုယ်တွင်းအဂ်ါများ၏ပြင်ပမှသက်ရောက်မှုကိုကာကွယ်ပေးခြင်း</li>
	<li>အအေးဓာတ်လွန်ကဲစွာခံစားရမှုကိုကာကွယ်ပေးခြင်း</li></b>
